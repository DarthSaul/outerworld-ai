#!/usr/bin/env node
// Writes packages/core/src/character-art.ts from docs/design/station-dashboard/sprites/art/*.png:
// each painted character as a PNG data URI, so core stays pure (no DOM, no asset pipeline) and the
// SPA draws them like any other sprite. Run after adding or changing art:
//   node scripts/character-art.mjs
// core's characters.test.ts fails when the module and the PNGs drift apart.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dir = join(root, "docs", "design", "station-dashboard", "sprites", "art");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".png"))
  .sort();

const entries = files.map((f) => {
  const id = f.replace(/\.png$/, "");
  const data = readFileSync(join(dir, f)).toString("base64");
  return `  "${id}": "data:image/png;base64,${data}",`;
});

const out = `// Generated by scripts/character-art.mjs from docs/design/station-dashboard/sprites/art/*.png.
// Do not edit: change the PNG and run \`node scripts/character-art.mjs\`.

/** Each painted character's art as a PNG data URI, by character id. */
export const CHARACTER_ART: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;
writeFileSync(join(root, "packages", "core", "src", "character-art.ts"), out);
console.log(`character-art: wrote ${files.length} characters`);
